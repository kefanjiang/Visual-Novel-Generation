// Bundles template/ into src/lib/template/generated.ts so the server can
// assemble game projects without touching the filesystem at runtime.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const templateDir = path.join(root, "template");
const outFile = path.join(root, "src/lib/template/generated.ts");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

export function buildTemplateSource() {
  const files = {};
  for (const full of walk(templateDir).sort()) {
    if (full.endsWith(".d.ts")) continue;
    const key = "/" + path.relative(templateDir, full).split(path.sep).join("/");
    files[key] = readFileSync(full, "utf8");
  }
  return (
    "// AUTO-GENERATED by scripts/gen-template.mjs — do not edit. Edit template/ and run `npm run gen:template`.\n" +
    `export const TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  writeFileSync(outFile, buildTemplateSource());
  console.log(`wrote ${path.relative(root, outFile)}`);
}
